/**
 * Regenerates src-tauri/src/i18n_table.rs from src/shared/i18n.ts so the Rust
 * side never keeps its own copy of the UI strings. Usage: pnpm gen:rust-i18n
 */
import { writeFileSync } from "node:fs";
import { dictionaries } from "../src/shared/i18n";

const languages = ["zh", "en", "ja", "ko"] as const;
const keys = Object.keys(dictionaries.zh).sort();

const rawString = (value: string): string => {
  let hashes = "#";
  while (value.includes(`"${hashes}`)) {
    hashes += "#";
  }
  return `r${hashes}"${value}"${hashes}`;
};

const rows = keys.map((key) => {
  const cells = languages.map((lang) => rawString(dictionaries[lang][key] ?? dictionaries.zh[key]));
  return `    (${JSON.stringify(key)}, [${cells.join(", ")}]),`;
});

writeFileSync(
  new URL("../src-tauri/src/i18n_table.rs", import.meta.url),
  `// Generated by scripts/gen-rust-i18n.ts from src/shared/i18n.ts. Do not edit.\n// Columns: zh, en, ja, ko. Sorted by key for binary search.\npub static TABLE: &[(&str, [&str; 4])] = &[\n${rows.join("\n")}\n];\n`
);
console.log(`wrote ${keys.length} keys`);
