import { readdir, readFile } from "node:fs/promises";
import { join, relative, sep } from "node:path";

const root = process.cwd();

// Usage-Pulse is a sidecar observer: it reads the IDE / CLI's own files and never writes to
// them. Every Rust file under the credentials/ and collectors/ directories is read-only
// code, so there is no allow-list there. Outside them, any file that mentions an IDE's files
// must not write either, with the single deliberate exception of history.rs (below).
const sensitiveHints = [
  "state.vscdb",
  ".credentials.json",
  "claude code-credentials",
  "cursorauth/accesstoken",
  // The Claude Code CLI session logs. Not a credential, but the same rule applies.
  "claude_config_dir",
  ".jsonl",
  "auth.json",
  // Directory / env forms only: the bare `.codex` substring also matches
  // `snapshot.codex` and would pull every third-service file into the scan.
  "~/.codex",
  "codex_home"
];

// Comments are stripped before scanning so prose cannot trip a hint.
const rustReadOnlyDirs = [join(root, "src-tauri", "src", "credentials"), join(root, "src-tauri", "src", "collectors")];
const rustWriteHints = [
  "fs::write(",
  "fs::remove",
  "fs::rename(",
  "fs::copy(",
  "fs::create_dir",
  "fs::set_permissions(",
  "file::create(",
  "file::create_new(",
  "openoptions",
  "remove_file(",
  "remove_dir",
  "set_len(",
  "write_all(",
  "sqlite_open_read_write",
  "sqlite_open_create",
  ".execute(",
  ".execute_batch(",
  "insert into",
  "update ",
  "delete from",
  "drop table",
  "trash",
  "add-generic-password",
  "delete-generic-password",
  "set-generic-password"
];

// Beyond those directories, any other Rust file that mentions an IDE's files
// must not write either. history.rs is the single, deliberate exception: the
// user-triggered "clear old history" button (see src-tauri/src/history.rs).
const rustSrcDir = join(root, "src-tauri", "src");
const rustAllowedWriters = new Set(["src-tauri/src/history.rs"]);
// Generated by `pnpm gen:rust-i18n`: a table of UI sentences, no code. Its prose
// legitimately says "update" and ".jsonl".
const rustDataOnly = new Set(["src-tauri/src/i18n_table.rs"]);

const stripRustComments = (source) => source.replace(/\/\*[\s\S]*?\*\//g, "").replace(/\/\/.*$/gm, "");

const listFiles = async (dir) => {
  const entries = await readdir(dir, { withFileTypes: true });
  const nested = await Promise.all(
    entries.map(async (entry) => {
      const fullPath = join(dir, entry.name);
      if (entry.isDirectory()) {
        return listFiles(fullPath);
      }
      return [fullPath];
    })
  );
  return nested.flat();
};

const main = async () => {
  const violations = [];
  const exercised = [];

  for (const dir of rustReadOnlyDirs) {
    let rustFiles = [];
    try {
      rustFiles = (await listFiles(dir)).filter((path) => path.endsWith(".rs"));
    } catch {
      continue;
    }
    for (const filePath of rustFiles) {
      const source = stripRustComments(await readFile(filePath, "utf-8")).toLowerCase();
      const writeMatch = rustWriteHints.find((hint) => source.includes(hint));
      if (writeMatch) {
        violations.push(`${filePath} (matched: ${writeMatch})`);
      }
    }
  }

  let rustSources = [];
  try {
    rustSources = (await listFiles(rustSrcDir)).filter((path) => path.endsWith(".rs"));
  } catch {
    rustSources = [];
  }
  for (const filePath of rustSources) {
    const relativePath = relative(root, filePath).split(sep).join("/");
    if (rustDataOnly.has(relativePath) || rustReadOnlyDirs.some((dir) => filePath.startsWith(dir))) {
      continue; // data-only, or already scanned above with no sensitive-hint gate
    }
    const source = stripRustComments(await readFile(filePath, "utf-8")).toLowerCase();
    if (!sensitiveHints.some((hint) => source.includes(hint))) {
      continue;
    }
    if (rustAllowedWriters.has(relativePath)) {
      exercised.push(`${relativePath} -> user-triggered history clean`);
      continue;
    }
    const writeMatch = rustWriteHints.find((hint) => source.includes(hint));
    if (writeMatch) {
      violations.push(`${filePath} (matched: ${writeMatch})`);
    }
  }

  if (violations.length > 0) {
    console.error("Readonly check failed. Sensitive credential paths must remain read-only:");
    for (const line of violations) {
      console.error(`- ${line}`);
    }
    process.exit(1);
  }

  for (const line of exercised) {
    console.log(`Readonly check: allowed exception in use - ${line}`);
  }
  console.log("Readonly check passed.");
};

main().catch((error) => {
  const message = error instanceof Error ? error.message : String(error);
  console.error(`Readonly check error: ${message}`);
  process.exit(1);
});
